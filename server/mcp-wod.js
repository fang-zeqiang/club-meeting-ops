import crypto from "node:crypto";

import { ApiError, bitableRequest } from "./bitable.js";
import { selectedMeeting } from "./mcp-agenda-read.js";
import { updateMeeting } from "./meetings-repository.js";
import { generateWod } from "./wod-generator.js";

const READ_ONLY = Object.freeze({ readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false });
const WRITE = Object.freeze({ readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false });
const REQUIRED_FIELDS = Object.freeze(["单词名", "音标", "词性", "单词释义", "单词例句"]);
const TOOL_NAMES = new Set(["vpe_random_wod", "vpe_list_wod_words", "vpe_add_wod", "vpe_update_wod", "vpe_remove_wod", "vpe_set_meeting_wod", "vpe_clear_meeting_wod"]);
const WORD_PROPERTIES = {
  word: { type: "string", minLength: 1, maxLength: 200 },
  pronunciation: { type: "string", minLength: 1, maxLength: 200 },
  part_of_speech: { type: "string", minLength: 1, maxLength: 100 },
  definition: { type: "string", minLength: 1, maxLength: 2000 },
  example: { type: "string", minLength: 1, maxLength: 2000 },
};
const WORD_KEYS = Object.keys(WORD_PROPERTIES);
const SELECTOR_PROPERTIES = {
  meeting_number: { type: "integer", minimum: 1 },
  meeting_reference: { type: "string", enum: ["today", "next"] },
};

export const WOD_TOOLS = Object.freeze([
  { name: "vpe_random_wod", title: "随机生成 Word of Tonight", description: "Randomly select one meeting-ready Word of Tonight from the configured Feishu Base word bank.", inputSchema: { type: "object", properties: {}, additionalProperties: false }, annotations: READ_ONLY },
  { name: "vpe_list_wod_words", title: "查询 WOD 词库", description: "List complete Word of Tonight records. Use wod_key for later updates or meeting selection.", inputSchema: { type: "object", properties: {}, additionalProperties: false }, annotations: READ_ONLY },
  { name: "vpe_add_wod", title: "新增 WOD", description: "Add one complete Word of Tonight record.", inputSchema: { type: "object", properties: WORD_PROPERTIES, required: WORD_KEYS, additionalProperties: false }, annotations: WRITE },
  { name: "vpe_update_wod", title: "更新 WOD", description: "Replace one Word of Tonight record by wod_key.", inputSchema: { type: "object", properties: { wod_key: { type: "string", minLength: 16, maxLength: 16 }, ...WORD_PROPERTIES }, required: ["wod_key", ...WORD_KEYS], additionalProperties: false }, annotations: WRITE },
  { name: "vpe_remove_wod", title: "删除 WOD", description: "Remove one Word of Tonight record by wod_key.", inputSchema: { type: "object", properties: { wod_key: { type: "string", minLength: 16, maxLength: 16 } }, required: ["wod_key"], additionalProperties: false }, annotations: WRITE },
  { name: "vpe_set_meeting_wod", title: "设置会议 WOD", description: "Set an active Agenda meeting's Word of Tonight snapshot. Usually pass only word: missing fields are generated by AI, and the reply shows the full card for the user to review. Alternatively pass wod_key to copy a word bank record, or any word fields to override specific values.", inputSchema: { type: "object", properties: { ...SELECTOR_PROPERTIES, wod_key: { type: "string", minLength: 16, maxLength: 16 }, ...WORD_PROPERTIES }, additionalProperties: false }, annotations: WRITE },
  { name: "vpe_clear_meeting_wod", title: "清空会议 WOD", description: "Clear every Word of Tonight snapshot field from an active Agenda meeting.", inputSchema: { type: "object", properties: SELECTOR_PROPERTIES, additionalProperties: false }, annotations: WRITE },
]);

function config() {
  const baseToken = String(process.env.WOD_BASE_TOKEN || "").trim();
  const tableId = String(process.env.WOD_TABLE_ID || "").trim();
  const missing = [!baseToken && "WOD_BASE_TOKEN", !tableId && "WOD_TABLE_ID"].filter(Boolean);
  if (missing.length) throw new ApiError(503, "WOD_NOT_CONFIGURED", "Word of Tonight persistence is not configured.", { missing });
  return { baseToken, tableId };
}

function recordsPath(baseToken, tableId, recordId = "") {
  const root = `/base/v3/bases/${encodeURIComponent(baseToken)}/tables/${encodeURIComponent(tableId)}/records`;
  return recordId ? `${root}/${encodeURIComponent(recordId)}` : `${root}?${new URLSearchParams({ limit: "200", offset: "0" })}`;
}

function wodKey(recordId) {
  return crypto.createHash("sha256").update(String(recordId || "")).digest("hex").slice(0, 16);
}

export function rowsFromBitablePage(data) {
  const fields = data?.fields || [];
  const rows = data?.data || [];
  if (!Array.isArray(fields) || !Array.isArray(rows)) throw new ApiError(502, "WOD_INVALID_RESPONSE", "Feishu returned an invalid Word of Tonight response.");
  return rows.map((values) => Object.fromEntries(fields.map((field, index) => [field, values[index]])));
}

function recordsFromBitablePage(data) {
  const rows = rowsFromBitablePage(data);
  const ids = data?.record_id_list || [];
  if (!Array.isArray(ids) || ids.length !== rows.length) throw new ApiError(502, "WOD_INVALID_RESPONSE", "Feishu returned Word of Tonight records without ids.");
  return rows.map((fields, index) => ({ recordId: String(ids[index] || ""), fields }));
}

function validFields(fields) {
  return REQUIRED_FIELDS.every((field) => String(fields[field] || "").trim());
}

function publicWord(record) {
  return { ...record.fields, wodKey: wodKey(record.recordId) };
}

async function listWodRecords() {
  const { baseToken, tableId } = config();
  const data = await bitableRequest(recordsPath(baseToken, tableId));
  if (data?.has_more) throw new ApiError(502, "WOD_INVALID_RESPONSE", "Word of Tonight pagination is not supported.");
  return recordsFromBitablePage(data).filter((record) => record.recordId && validFields(record.fields));
}

export async function listWodWords() {
  return (await listWodRecords()).map(publicWord);
}

function wodFields(input) {
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new ApiError(400, "INVALID_WOD", "A complete Word of Tonight record is required.");
  const fields = Object.fromEntries(REQUIRED_FIELDS.map((field) => [field, String(input[field] || "").trim()]));
  if (!validFields(fields)) throw new ApiError(400, "INVALID_WOD", "单词名、音标、词性、单词释义和单词例句均为必填项。");
  return fields;
}

function wodFieldsFromArgs(args) {
  return wodFields({ 单词名: args.word, 音标: args.pronunciation, 词性: args.part_of_speech, 单词释义: args.definition, 单词例句: args.example });
}

async function wordRecord(key) {
  if (!/^[a-f0-9]{16}$/.test(String(key || ""))) throw new ApiError(400, "INVALID_WOD_KEY", "wod_key is invalid.");
  const record = (await listWodRecords()).find((candidate) => wodKey(candidate.recordId) === key);
  if (!record) throw new ApiError(404, "WOD_NOT_FOUND", "Word of Tonight was not found.");
  return record;
}

export async function createWod(input) {
  const { baseToken, tableId } = config();
  const fields = wodFields(input);
  const data = await bitableRequest(recordsPath(baseToken, tableId), { method: "POST", body: JSON.stringify(fields) });
  const recordId = data?.record_id || data?.record_id_list?.[0];
  const record = recordId && (await listWodRecords()).find((candidate) => candidate.recordId === recordId);
  if (!record) throw new ApiError(502, "WOD_READ_AFTER_WRITE_FAILED", "Word of Tonight was saved but could not be read back.");
  return publicWord(record);
}

export async function updateWod(key, input) {
  const { baseToken, tableId } = config();
  const record = await wordRecord(key);
  await bitableRequest(recordsPath(baseToken, tableId, record.recordId), { method: "PATCH", body: JSON.stringify(wodFields(input)) });
  return publicWord(await wordRecord(key));
}

export async function removeWod(key) {
  const { baseToken, tableId } = config();
  const record = await wordRecord(key);
  await bitableRequest(recordsPath(baseToken, tableId, record.recordId), { method: "DELETE" });
}

export function pickWod(words, randomIndex = (length) => crypto.randomInt(length)) {
  if (!words.length) throw new ApiError(404, "WOD_WORD_BANK_EMPTY", "The Word of Tonight word bank is empty.");
  return words[randomIndex(words.length)];
}

export function formatWod(word) {
  return [`${word["单词名"]} (${word["词性"]})`, `Pronunciation: ${word["音标"]}`, `Meaning: ${word["单词释义"]}`, `Example: ${word["单词例句"]}`].join("\n");
}

function objectArgs(raw, allowed) {
  const args = raw == null ? {} : raw;
  if (typeof args !== "object" || Array.isArray(args) || Object.keys(args).some((key) => !allowed.includes(key))) throw new ApiError(400, "INVALID_ARGUMENTS", `Use only ${allowed.join(", ") || "an empty object"}.`);
  return args;
}

function snapshot(record) {
  return { word: record.fields["单词名"], pronunciation: record.fields["音标"], partOfSpeech: record.fields["词性"], definition: record.fields["单词释义"], example: record.fields["单词例句"] };
}

// 只给单词时由 AI 补全整张单词卡；线上词库读不通（飞书 91402 NOTEXIST），不再先查词库
export async function autofillWod(rawWord, { generate = generateWod } = {}) {
  const word = String(rawWord || "").trim();
  if (!word) throw new ApiError(400, "INVALID_WOD_WORD", "请先填写单词。");
  return { source: "ai", wordOfDay: await generate(word) };
}

const DIRECT_FIELD_NAMES = { pronunciation: "pronunciation", part_of_speech: "partOfSpeech", definition: "definition", example: "example" };

async function resolveMeetingWod(args) {
  const hasKey = args.wod_key != null;
  const hasDirect = WORD_KEYS.some((key) => args[key] != null);
  if (hasKey && hasDirect) throw new ApiError(400, "INVALID_ARGUMENTS", "Use either wod_key or word fields, not both.");
  if (hasKey) return { source: "word_bank", wordOfDay: snapshot(await wordRecord(args.wod_key)) };
  if (!hasDirect) throw new ApiError(400, "INVALID_ARGUMENTS", "Provide wod_key, or at least word (missing fields are auto-filled).");
  if (WORD_KEYS.every((key) => String(args[key] ?? "").trim())) return { source: "direct", wordOfDay: snapshot({ fields: wodFieldsFromArgs(args) }) };
  const filled = await autofillWod(args.word);
  const provided = Object.entries(DIRECT_FIELD_NAMES).filter(([arg]) => String(args[arg] ?? "").trim()).map(([arg, key]) => [key, String(args[arg]).trim()]);
  return { source: filled.source, wordOfDay: { ...filled.wordOfDay, ...Object.fromEntries(provided) } };
}

function setWodMessage(meetingNumber, wordOfDay, source) {
  const card = [
    `${wordOfDay.word}${wordOfDay.partOfSpeech ? ` (${wordOfDay.partOfSpeech})` : ""}`,
    wordOfDay.pronunciation && `Pronunciation: ${wordOfDay.pronunciation}`,
    wordOfDay.definition && `Meaning: ${wordOfDay.definition}`,
    wordOfDay.usage && `Usage: ${wordOfDay.usage}`,
    wordOfDay.example && `Example: ${wordOfDay.example}`,
  ].filter(Boolean).join("\n");
  const note = source === "ai"
    ? "\n\n以上内容由 AI 生成，请向用户展示并请其核对；如需修改，用 vpe_set_meeting_wod 传入要改的字段。"
    : source === "word_bank" ? "\n\n内容来自 WOD 词库。" : "";
  return `已设置 #${meetingNumber} 的 WOD：\n${card}${note}`;
}

async function changeMeetingWod(rawArguments, clear) {
  const allowed = clear ? ["meeting_number", "meeting_reference"] : ["meeting_number", "meeting_reference", "wod_key", ...WORD_KEYS];
  const { args, meeting } = await selectedMeeting(rawArguments, allowed);
  if (meeting.status === "archived") throw new ApiError(404, "MEETING_NOT_FOUND", "Active meeting was not found.");
  if (clear) {
    const updated = await updateMeeting(meeting.id, { ...meeting, wordOfDay: { word: "", pronunciation: "", partOfSpeech: "", definition: "", example: "" } }, meeting.revision);
    return { data: { meetingNumber: updated.meetingNumber, wordOfDay: updated.wordOfDay }, message: `已清空 #${updated.meetingNumber} 的 WOD。` };
  }
  const { source, wordOfDay } = await resolveMeetingWod(args);
  const updated = await updateMeeting(meeting.id, { ...meeting, wordOfDay }, meeting.revision);
  return { data: { meetingNumber: updated.meetingNumber, wordOfDay: updated.wordOfDay, source }, message: setWodMessage(updated.meetingNumber, updated.wordOfDay, source) };
}

export async function callWodTool(name, rawArguments) {
  if (!TOOL_NAMES.has(name)) return null;
  if (name === "vpe_random_wod") {
    objectArgs(rawArguments, []);
    const words = await listWodWords();
    const word = pickWod(words);
    return { data: { ...word, totalWords: words.length }, message: formatWod(word) };
  }
  if (name === "vpe_list_wod_words") {
    objectArgs(rawArguments, []);
    const words = await listWodWords();
    return { data: { words, totalWords: words.length }, message: `共有 ${words.length} 个 WOD。` };
  }
  if (name === "vpe_add_wod") {
    const args = objectArgs(rawArguments, WORD_KEYS);
    return { data: await createWod(wodFieldsFromArgs(args)), message: "已添加 WOD。" };
  }
  if (name === "vpe_update_wod") {
    const args = objectArgs(rawArguments, ["wod_key", ...WORD_KEYS]);
    return { data: await updateWod(args.wod_key, wodFieldsFromArgs(args)), message: "已更新 WOD。" };
  }
  if (name === "vpe_remove_wod") {
    const args = objectArgs(rawArguments, ["wod_key"]);
    await removeWod(args.wod_key);
    return { data: { deleted: true }, message: "已删除 WOD。" };
  }
  return changeMeetingWod(rawArguments, name === "vpe_clear_meeting_wod");
}
